def _call_openai(prompt: str) -> str:
    url = settings.ai_base_url.rstrip("/") + "/chat/completions"
    headers = {
        "Authorization": f"Bearer {settings.openai_api_key}",
        "Content-Type": "application/json",
    }
    body = {
        "model": settings.openai_model,
        "messages": [
            {
                "role": "system",
                "content": (
                    "You are Eventora AI, a meticulous event planner. You always "
                    "respond with valid JSON only â€” no prose, no markdown fences."
                ),
            },
            {"role": "user", "content": prompt},
        ],
        "temperature": 0.4,
        "response_format": {"type": "json_object"},
    }
    with httpx.Client(timeout=settings.ai_timeout_seconds) as client:
        response = client.post(url, headers=headers, json=body)
        response.raise_for_status()
        data = response.json()
    return str(data["choices"][0]["message"]["content"])


def _call_anthropic(prompt: str) -> str:
    url = "https://api.anthropic.com/v1/messages"
    headers = {
        "x-api-key": settings.anthropic_api_key,
        "anthropic-version": "2023-06-01",
        "Content-Type": "application/json",
    }
    body = {
        "model": settings.anthropic_model,
        "max_tokens": 4000,
        "temperature": 0.4,
        "system": (
            "You are Eventora AI, a meticulous event planner. You always respond "
            "with valid JSON only â€” no prose, no markdown fences."
        ),
        "messages": [{"role": "user", "content": prompt}],
    }
    with httpx.Client(timeout=settings.ai_timeout_seconds) as client:
        response = client.post(url, headers=headers, json=body)
        response.raise_for_status()
        data = response.json()
    blocks = data.get("content", [])
    for block in blocks:
        if block.get("type") == "text":
            return str(block["text"])
    raise AIServiceError("Anthropic response contained no text block.")


def _call_provider(prompt: str) -> str:
    if settings.ai_provider == "openai":
        return _call_openai(prompt)
    if settings.ai_provider == "anthropic":
        return _call_anthropic(prompt)
    raise AIServiceError(f"Unsupported AI provider: {settings.ai_provider}")


def generate_plan(
    event: dict[str, Any],
    extra_instructions: str = "",
) -> dict[str, Any]:
    """Generate a structured plan, falling back to the deterministic planner.

    Returns a dict with ``plan``, ``source`` ("ai" or "fallback"), ``provider``,
    ``model`` and ``notice``.
    """
    provider = settings.ai_provider
    model = (
        settings.openai_model
        if provider == "openai"
        else settings.anthropic_model
        if provider == "anthropic"
        else "deterministic-planner"
    )

    if not settings.ai_available:
        return {
            "plan": generate_deterministic_plan(event),
            "source": "fallback",
            "provider": "none",
            "model": "deterministic-planner",
            "notice": FALLBACK_NOTICE,
        }

    try:
        raw = _call_provider(_build_prompt(event, extra_instructions))
        parsed = _extract_json(raw)
        validated = EventPlanSchema.model_validate(parsed)
    except Exception as exc:  # noqa: BLE001 - any provider/validation failure falls back
        return {
            "plan": generate_deterministic_plan(event),
            "source": "fallback",
            "provider": provider,
            "model": model,
            "notice": FALLBACK_NOTICE + f" The provider error was: {type(exc).__name__}.",
        }

    plan = validated.to_payload()
    plan["_meta"] = {
        "provider": provider,
        "model": model,
        "generated_at": _now_iso(),
    }
    return {
        "plan": plan,
        "source": "ai",
        "provider": provider,
        "model": model,
        "notice": AI_NOTICE,
    }


def _now_iso() -> str:
    from datetime import datetime, timezone


def _build_chat_prompt(
    message: str,
    event: dict[str, Any] | None,
    history: list[dict[str, str]],
) -> str:
    context = (
        json.dumps(event, indent=2, default=str)
        if event
        else "No event is currently selected."
    )
    turns = "\n".join(
        f"{h.get('role', 'user').capitalize()}: {h.get('content', '')}" for h in history[-8:]
    )
    return (
        "You are Eventora AI, a practical celebration planner helping a user plan "
        "an event. Answer clearly and concisely, and use INR for all amounts. If you "
        "are unsure of a specific market price, say so and suggest checking vendor "
        "quotes.\n\n"
        f"CURRENT EVENT:\n{context}\n\n"
        f"CONVERSATION SO FAR:\n{turns or '(none)'}\n\n"
        f"USER QUESTION:\n{message}\n"
    )


def chat(
    message: str,
    event: dict[str, Any] | None = None,
    history: list[dict[str, str]] | None = None,
) -> dict[str, Any]:
    """Answer a planning question, falling back to a deterministic reply."""
    history = history or []
    provider = settings.ai_provider
    model = (
        settings.openai_model
        if provider == "openai"
        else settings.anthropic_model
        if provider == "anthropic"
        else "deterministic-planner"
    )

    if not settings.ai_available:
        return {
            "reply": _deterministic_reply(message, event),
            "source": "fallback",
            "provider": "none",
            "model": "deterministic-planner",
            "notice": FALLBACK_NOTICE,
        }

    try:
        raw = _call_provider(_build_chat_prompt(message, event, history))
        reply = raw.strip()
        if not reply:
            raise AIServiceError("Empty response from provider.")
    except Exception as exc:  # noqa: BLE001
        return {
            "reply": _deterministic_reply(message, event),
            "source": "fallback",
            "provider": provider,
            "model": model,
            "notice": FALLBACK_NOTICE + f" The provider error was: {type(exc).__name__}.",
        }

    return {
        "reply": reply,
        "source": "ai",
        "provider": provider,
        "model": model,
        "notice": AI_NOTICE,
    }




def _deterministic_reply(message: str, event: dict[str, Any] | None) -> str:
    """A helpful, rule-based answer that needs no API key."""
    if event is None:
        return (
            "No event is selected yet, so I can only give general guidance. "
            "Create or open an event and I can talk through its budget, checklist, "
            "timeline and day-of schedule. For specific prices, always confirm with "
            "vendors â€” the estimates in this app come from a synthetic cost model."
        )

    from app.ml.dataset import compute_total_cost

    guests = int(event.get("guest_count", 0) or 0)
    breakdown = compute_total_cost(
        event_type=event.get("event_type", "wedding"),
        guest_count=guests,
        city=event.get("city", "tier2_city"),
        venue_type=event.get("venue_type", "banquet_hall"),
        duration_hours=int(event.get("duration_hours", 5) or 5),
        catering_level=event.get("catering_level", "standard"),
        decoration_level=event.get("decoration_level", "standard"),
        photography=event.get("photography", "standard"),
    )
    budget = float(event.get("budget", 0) or 0)
    per_guest = breakdown["total"] / guests if guests else 0.0

    lowered = message.lower()
    if any(word in lowered for word in ("cost", "budget", "price", "expensive", "afford")):
        usage = (
            f" That is about {((breakdown['total'] / budget) * 100):.0f}% of your "
            f"INR {budget:,.0f} budget."
            if budget > 0
            else " Set a budget in the app to compare it against a target."
        )
        return (
            f"Based on the cost model, {event.get('name', 'your event')} for {guests} "
            f"guests is estimated at INR {breakdown['total']:,.0f} total, or roughly "
            f"INR {per_guest:,.0f} per guest.{usage}\n\n"
            f"The largest line is catering at INR {breakdown['catering']:,.0f}, "
            f"followed by the venue at INR {breakdown['venue']:,.0f}. "
            "These come from a synthetic cost model trained on documented rules, so "
            "treat them as a planning range and confirm with vendor quotes."
        )

    if any(word in lowered for word in ("checklist", "task", "todo", "to-do")):
        return (
            "Your checklist is organised into the stages that usually decide whether "
            "an event lands well: venue, catering, decor, photography, attire, "
            "invitations, guest travel and stay, entertainment, logistics, safety and "
            "hygiene, plus an on-the-day list. The rule of thumb is to book the venue "
            "first â€” every other vendor depends on the date and the capacity â€” then "
            "lock catering once the headcount is realistic."
        )

    if any(word in lowered for word in ("timeline", "when", "schedule", "order", "plan")):
        return (
            "The timeline runs backwards from your event date: define the plan and "
            "shortlist at around 90 days out, book the venue by 75 days, lock the date "
            "and headcount by 60 days, compare vendor quotes by 55 days, book catering "
            "by 45 days, send invitations by 40 days, confirm decor and florals by 30 "
            "days, and finalise the run sheet a week before. The event day itself "
            "covers setup, guest arrival, the programme, food, entertainment, cake and "
            "vendor settlement."
        )

    return (
        f"For {event.get('name', 'your event')} on {event.get('event_date', 'your date')}, "
        f"here are the numbers that matter most: {guests} guests, an estimated total of "
        f"INR {breakdown['total']:,.0f} (about INR {per_guest:,.0f} per guest), and a "
        f"{event.get('duration_hours', 5)}-hour programme in "
        f"{event.get('venue_type', 'a venue').replace('_', ' ')}.\n\n"
        "Open the Plan tab for the full checklist and timeline, the Budget tab for the "
        "cost breakdown and risk assessment, and the Insights tab for AI "
        "recommendations matched to your preferences."
    )

